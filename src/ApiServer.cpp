#include "ApiServer.h"

#include <httplib.h>

#include <functional>

using nlohmann::json;

namespace {

void send(httplib::Response& res, const ServiceResult& r) {
    res.status = r.status;
    res.set_content(r.body.dump(), "application/json; charset=utf-8");
}

void sendError(httplib::Response& res, int status, const std::string& code, const std::string& msg) {
    send(res, BankService::error(status, code, msg));
}

// Parses the request body as JSON. Empty body -> empty object (allowed for some routes).
bool parseBody(const httplib::Request& req, httplib::Response& res, json& out) {
    if (req.body.empty()) { out = json::object(); return true; }
    out = json::parse(req.body, nullptr, /*allow_exceptions=*/false);
    if (out.is_discarded()) {
        sendError(res, 400, "MALFORMED_JSON", "Request body is not valid JSON");
        return false;
    }
    return true;
}

std::string param(const httplib::Request& req, const char* name) {
    return req.has_param(name) ? req.get_param_value(name) : "";
}

}  // namespace

ApiServer::ApiServer(BankService& service, std::string frontendDir)
    : service_(service), frontendDir_(std::move(frontendDir)), server_(std::make_unique<httplib::Server>()) {
    registerRoutes();
}

ApiServer::~ApiServer() = default;

void ApiServer::registerRoutes() {
    httplib::Server& s = *server_;
    BankService& svc = service_;
    s.set_payload_max_length(64 * 1024);  // bank requests are tiny; reject anything large

    auto get = [&](const char* pattern, std::function<ServiceResult(const httplib::Request&)> fn) {
        s.Get(pattern, [fn](const httplib::Request& req, httplib::Response& res) { send(res, fn(req)); });
    };
    auto post = [&](const char* pattern,
                    std::function<ServiceResult(const httplib::Request&, const json&)> fn) {
        s.Post(pattern, [fn](const httplib::Request& req, httplib::Response& res) {
            json body;
            if (parseBody(req, res, body)) send(res, fn(req, body));
        });
    };

    // Open health check for hosting platforms (no data, no login needed).
    s.Get("/healthz", [](const httplib::Request&, httplib::Response& res) { res.set_content("ok", "text/plain"); });

    get("/api/dashboard", [&](const httplib::Request&) { return svc.dashboard(); });
    get("/api/account-types", [&](const httplib::Request&) { return svc.accountTypes(); });
    get("/api/accounts/sorted", [&](const httplib::Request& r) {   // must be registered before the {n} route
        return svc.sortedAccounts(param(r, "by"), param(r, "order"));
    });
    get("/api/accounts", [&](const httplib::Request& r) { return svc.listAccounts(param(r, "search")); });
    get(R"(/api/accounts/([^/]+))", [&](const httplib::Request& r) { return svc.getAccount(r.matches[1]); });
    post("/api/accounts", [&](const httplib::Request&, const json& b) { return svc.createAccount(b); });
    s.Delete(R"(/api/accounts/([^/]+))", [&](const httplib::Request& req, httplib::Response& res) {
        send(res, svc.closeAccount(req.matches[1]));
    });

    post("/api/transactions/deposit", [&](const httplib::Request&, const json& b) { return svc.deposit(b); });
    post("/api/transactions/withdraw", [&](const httplib::Request&, const json& b) { return svc.withdraw(b); });
    post("/api/transactions/transfer", [&](const httplib::Request&, const json& b) { return svc.transfer(b); });
    post("/api/transactions/reverse", [&](const httplib::Request&, const json& b) { return svc.reverse(b); });
    get("/api/transactions/reversible", [&](const httplib::Request&) { return svc.nextReversible(); });
    get(R"(/api/transactions/account/([^/]+))", [&](const httplib::Request& r) { return svc.accountTransactions(r.matches[1]); });
    get("/api/transactions", [&](const httplib::Request& r) { return svc.recentTransactions(param(r, "limit")); });

    get("/api/queue", [&](const httplib::Request&) { return svc.queue(); });
    post("/api/queue", [&](const httplib::Request&, const json& b) { return svc.issueToken(b); });
    post("/api/queue/serve", [&](const httplib::Request&, const json&) { return svc.serveNext(); });

    // Frontend files are served from the same origin, so no CORS configuration is needed.
    if (!s.set_mount_point("/", frontendDir_))
        std::fprintf(stderr, "Warning: frontend folder '%s' not found\n", frontendDir_.c_str());

    s.set_error_handler([](const httplib::Request& req, httplib::Response& res) {
        // Only replace errors generated by the HTTP library itself. Responses built by
        // BankService already carry a specific JSON message, which must be kept.
        if (req.path.rfind("/api/", 0) == 0 && res.body.empty()) {
            const std::string msg = res.status == 404 ? "Unknown API route or method" : "Request could not be processed";
            sendError(res, res.status == 0 ? 500 : res.status, res.status == 404 ? "NOT_FOUND" : "BAD_REQUEST", msg);
        }
    });
    s.set_exception_handler([](const httplib::Request&, httplib::Response& res, std::exception_ptr) {
        sendError(res, 500, "INTERNAL_ERROR", "Unexpected server error");
    });
    s.set_post_routing_handler([](const httplib::Request& req, httplib::Response& res) {
        res.set_header("X-Content-Type-Options", "nosniff");
        if (req.path.rfind("/api/", 0) == 0) res.set_header("Cache-Control", "no-store");
    });
}

bool ApiServer::listen(const std::string& host, int port) { return server_->listen(host, port); }
void ApiServer::stop() { server_->stop(); }

void ApiServer::requireLogin(const std::string& user, const std::string& password) {
    const std::string expected = "Basic " + httplib::detail::base64_encode(user + ":" + password);
    server_->set_pre_routing_handler([expected](const httplib::Request& req, httplib::Response& res) {
        if (req.path == "/healthz") return httplib::Server::HandlerResponse::Unhandled;
        const std::string given = req.get_header_value("Authorization");
        // Compare every byte (no early exit) so timing does not reveal how much matched.
        unsigned char diff = given.size() == expected.size() ? 0 : 1;
        for (std::size_t i = 0; i < given.size() && i < expected.size(); ++i)
            diff |= static_cast<unsigned char>(given[i] ^ expected[i]);
        if (diff == 0) return httplib::Server::HandlerResponse::Unhandled;
        res.status = 401;
        res.set_header("WWW-Authenticate", "Basic realm=\"Bank Management System\", charset=\"UTF-8\"");
        res.set_content("Login required", "text/plain");
        return httplib::Server::HandlerResponse::Handled;
    });
}
